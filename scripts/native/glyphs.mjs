#!/usr/bin/env node
/**
 * Writes the glyphs that Monarch for Android draws itself (CROSS-PLATFORM.md section 3): every row of
 * platforms/icons.json with `bundled: true` becomes an `ImageVector` in
 * platforms/android/monarch-compose/src/main/kotlin/com/rookhq/monarch/internal/MonarchGlyphs.kt, built from
 * the vendored Material Symbols Outlined SVG platforms/android/glyphs/material-symbols-outlined/<android>.svg
 * (Apache-2.0, Google; THIRD_PARTY_NOTICES.md). Components use them as defaults where the web component draws
 * its own glyph (a banner's tone icon, an edit pencil, a chevron), so no app has to pass one.
 *
 * Usage: node scripts/native/glyphs.mjs [--check]
 *   --check  write nothing; fail when MonarchGlyphs.kt is stale or an SVG is missing.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const table = JSON.parse(readFileSync(join(root, 'platforms', 'icons.json'), 'utf8'));
const svgDir = join(root, 'platforms', 'android', 'glyphs', 'material-symbols-outlined');
const target = join(
  root,
  'platforms/android/monarch-compose/src/main/kotlin/com/rookhq/monarch/internal/MonarchGlyphs.kt',
);

export const pascal = (name) =>
  name
    .split(/[_-]/)
    .filter(Boolean)
    .map((p) => p[0].toUpperCase() + p.slice(1))
    .join('');

/** The bundled Material Symbols names, sorted and unique. */
export function bundledGlyphs() {
  return [
    ...new Set(
      [...table.icons, ...(table.extra ?? [])].filter((i) => i.bundled).map((i) => i.android),
    ),
  ].sort();
}

const problems = [];
const entries = bundledGlyphs().map((name) => {
  const file = join(svgDir, `${name}.svg`);
  if (!existsSync(file)) {
    problems.push(`${relative(root, file)} is missing (bundled in platforms/icons.json)`);
    return null;
  }
  const svg = readFileSync(file, 'utf8');
  const viewBox = /viewBox="([^"]+)"/.exec(svg)?.[1];
  const paths = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((m) => m[1]);
  if (viewBox !== '0 -960 960 960' || paths.length === 0) {
    problems.push(`${relative(root, file)}: expected one or more paths on the 0 -960 960 960 grid`);
    return null;
  }
  return { name, id: pascal(name), paths };
});

const autoMirrored = new Set(['keyboard_arrow_left', 'keyboard_arrow_right']);
const body = entries
  .filter(Boolean)
  .map(({ name, id, paths }) => {
    const adds = paths.map((d) => `            "${d}",`).join('\n');
    return (
      `    /** Material Symbols Outlined \`${name}\`. */\n` +
      `    val ${id}: ImageVector by lazy {\n` +
      `        glyph(\n            name = "${id}",\n            autoMirror = ${autoMirrored.has(name)},\n${adds}\n        )\n    }\n`
    );
  })
  .join('\n');

const content = `// Generated by scripts/native/glyphs.mjs from platforms/icons.json and
// platforms/android/glyphs/material-symbols-outlined/*.svg. Do not edit.
// Material Symbols: Copyright Google LLC, Apache License 2.0 (THIRD_PARTY_NOTICES.md).
package com.rookhq.monarch.internal

import androidx.compose.ui.graphics.Color
import androidx.compose.ui.graphics.SolidColor
import androidx.compose.ui.graphics.vector.ImageVector
import androidx.compose.ui.graphics.vector.addPathNodes
import androidx.compose.ui.graphics.vector.group
import androidx.compose.ui.unit.dp

/**
 * The glyphs Monarch draws itself because the web component draws them (tone icons, the edit pencil, chevrons,
 * close, lock, check), so a component shows them by default as on the web and on iOS. Outlined, 24dp grid,
 * tinted by the caller (\`MonarchIcon\` uses the content colour). Not public: apps bring their own icon set.
 */
internal object MonarchGlyphs {
${body}
    private fun glyph(name: String, autoMirror: Boolean, vararg paths: String): ImageVector =
        ImageVector.Builder(
            name = "MonarchGlyph.$name",
            defaultWidth = GRID_DP.dp,
            defaultHeight = GRID_DP.dp,
            viewportWidth = VIEWPORT,
            viewportHeight = VIEWPORT,
            autoMirror = autoMirror,
        ).apply {
            // The SVGs are drawn on 0 -960 960 960: move them down into the viewport.
            group(translationY = VIEWPORT) {
                paths.forEach { data ->
                    addPath(pathData = addPathNodes(data), fill = SolidColor(Color(red = 0f, green = 0f, blue = 0f)))
                }
            }
        }.build()

    private const val GRID_DP = 24
    private const val VIEWPORT = 960f
}
`;

if (problems.length) {
  console.error(`glyphs: ${problems.length} problem(s)\n  ${problems.join('\n  ')}`);
  process.exit(1);
}
const current = existsSync(target) ? readFileSync(target, 'utf8') : null;
if (process.argv.includes('--check')) {
  if (current !== content) {
    console.error(`glyphs: ${relative(root, target)} is stale. Run npm run native:glyphs`);
    process.exit(1);
  }
  console.log(`glyphs: ${entries.length} bundled Android glyphs; up to date`);
} else if (current !== content) {
  writeFileSync(target, content);
  console.log(`glyphs: wrote ${relative(root, target)} (${entries.length} glyphs)`);
} else {
  console.log(`glyphs: ${entries.length} bundled Android glyphs; up to date`);
}
