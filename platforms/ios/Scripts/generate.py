#!/usr/bin/env python3
"""Generates every shared file of Monarch for iOS from per-component files.

Adding a component only adds files. Everything that would otherwise be a
shared, hand-edited list is written by this script:

  inventory/<id>.json                       ->  components.json
  inventory/<id>.json (examples)            ->  Tests/MonarchUITests/Generated/Examples/*Examples.generated.swift
                                                (stable) and *ExperimentalExamples.generated.swift
                                                (compiled with `@_spi(Experimental) import MonarchUI`)
  enum ...: ComponentFixtures in the tests  ->  Tests/MonarchUITests/Generated/FixtureRegistry.generated.swift

The cross-platform parity fixtures (Tests/MonarchUITests/Generated/Fixtures) and the code of an example bound to
one are written by scripts/native/fixtures.mjs; this script checks the binding.
  struct ...: CataloguePage in the sample   ->  Sample/Sources/Generated/CatalogueRegistry.generated.swift

It also validates every inventory file against inventory/schema.json and
checks the conventions in docs/ADDING-COMPONENTS.md.

Usage, from anywhere:
  Scripts/generate.py                  validate and rewrite the generated files
  Scripts/generate.py --check          validate and fail if a generated file is stale
  Scripts/generate.py --resolve NAME   print the inventory ids for a Swift type name, a title or an id
  Scripts/generate.py --suites NAME    print the test suites of that component, one per line
  Scripts/generate.py --files NAME     print the hand-written Swift files of that component, one per line
  Scripts/generate.py --parity         compare the inventory with ../parity.json (report only)

Standard library only. Runs on the python3 that ships with Xcode.
"""

import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
INVENTORY = os.path.join(ROOT, "inventory")
SOURCES = os.path.join(ROOT, "Sources", "MonarchUI")
TESTS = os.path.join(ROOT, "Tests", "MonarchUITests")
SAMPLE = os.path.join(ROOT, "Sample", "Sources")
HEADER = "// Generated by Scripts/generate.py. Do not edit.\n"

errors = []


def error(message):
    errors.append(message)


def read(path):
    with open(path, encoding="utf-8") as handle:
        return handle.read()


def pascal(text):
    """button -> Button, data-display -> DataDisplay."""
    return "".join(part[:1].upper() + part[1:] for part in re.split(r"[-_ ]+", text) if part)


def family_folder(family):
    """The folder of a web family. The one crm component lives under Workflow."""
    return "Workflow" if family == "crm" else pascal(family)


# --- Schema validation -------------------------------------------------------

TYPES = {
    "object": dict, "array": list, "string": str, "boolean": bool, "null": type(None),
}


def validate(value, schema, where):
    kinds = schema.get("type")
    if kinds is not None:
        kinds = kinds if isinstance(kinds, list) else [kinds]
        if not any(isinstance(value, TYPES[kind]) for kind in kinds):
            error("%s: expected %s" % (where, " or ".join(kinds)))
            return
    if "enum" in schema and value not in schema["enum"]:
        error("%s: %r is not one of %s" % (where, value, ", ".join(schema["enum"])))
    if isinstance(value, str):
        if len(value.strip()) < schema.get("minLength", 0):
            error("%s: must not be empty" % where)
        if "pattern" in schema and not re.search(schema["pattern"], value):
            error("%s: %r does not match %s" % (where, value, schema["pattern"]))
    elif isinstance(value, list):
        if len(value) < schema.get("minItems", 0):
            error("%s: needs at least %d item(s)" % (where, schema["minItems"]))
        for index, item in enumerate(value):
            validate(item, schema.get("items", {}), "%s[%d]" % (where, index))
    elif isinstance(value, dict):
        properties = schema.get("properties", {})
        for key in schema.get("required", []):
            if key not in value:
                error("%s: missing field %r" % (where, key))
        for key, item in value.items():
            if key in properties:
                validate(item, properties[key], "%s.%s" % (where, key))
            elif schema.get("additionalProperties") is False:
                error("%s: unknown field %r" % (where, key))


def load_inventory():
    schema = json.loads(read(os.path.join(INVENTORY, "schema.json")))
    entries = []
    for name in sorted(os.listdir(INVENTORY)):
        if not name.endswith(".json") or name == "schema.json":
            continue
        where = "inventory/" + name
        try:
            entry = json.loads(read(os.path.join(INVENTORY, name)))
        except ValueError as problem:
            error("%s: not valid JSON: %s" % (where, problem))
            continue
        before = len(errors)
        validate(entry, schema, where)
        if len(errors) > before:
            continue
        if entry["id"] + ".json" != name:
            error("%s: id %r must equal the file name" % (where, entry["id"]))
        check_coverage_rules(entry, where)
        entries.append(entry)
    return entries


def check_coverage_rules(entry, where):
    coverage, name = entry["coverage"], entry["name"]
    if coverage in ("build", "style"):
        if not name:
            error("%s: coverage %s needs a Swift name" % (where, coverage))
        if not entry["tests"]:
            error("%s: coverage %s needs at least one test suite in tests" % (where, coverage))
    if coverage in ("native", "compose", "web-only") and name:
        error("%s: coverage %s ships no Swift type, so name must be null" % (where, coverage))
    if coverage == "web-only":
        if entry["kind"] != "none":
            error("%s: coverage web-only needs kind none" % where)
    else:
        if not entry["wrapsNative"]:
            error("%s: wrapsNative must name the SwiftUI API" % where)
        if not entry["examples"]:
            error("%s: coverage %s needs at least one compiled example" % (where, coverage))
    if entry["layer"] == "patterns" and entry["status"] != "experimental":
        error("%s: layer patterns needs status experimental, not %s (ADR 0017)" % (where, entry["status"]))
    if coverage == "native" and (entry["kind"] != "native" or entry["category"] != "A"):
        error("%s: coverage native needs kind native and category A" % where)
    if coverage == "compose" and entry["kind"] != "recipe":
        error("%s: coverage compose needs kind recipe" % where)
    if coverage == "build" and entry["family"] != "foundations":
        folder = os.path.join(SOURCES, "Components", family_folder(entry["family"]), name or "")
        if not os.path.isfile(os.path.join(folder, (name or "") + ".swift")):
            error("%s: expected the component at %s/%s.swift"
                  % (where, os.path.relpath(folder, ROOT), name))


# --- Generated files ---------------------------------------------------------

def components_json(entries):
    return json.dumps(entries, indent=2, ensure_ascii=False) + "\n"


def indent(text, spaces):
    pad = " " * spaces
    return "\n".join(pad + line if line.strip() else "" for line in text.split("\n"))


def swift_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def is_experimental_example(entry, example):
    """An example of an experimental entry, or one that opts in because it uses an experimental symbol."""
    return entry["status"] == "experimental" or bool(example.get("experimental"))


def start_presented(entry_id, setup, names):
    """The setup of an example for the preview host: each `@State` variable in `names` starts presented.

    A name is `isShown` (starts true) or `selected=1` (starts as the given expression). In the app and in the tests
    `PreviewMode.presented` is false, so the example is unchanged; the preview host sets it so the sheet, alert,
    dialog or popover is open in the screenshot. The documentation shows the example's `code` and `setup` as written.
    """
    for item in names:
        name, _, value = item.partition("=")
        pattern = re.compile(r"(@State\s+private\s+var\s+%s\b[^=\n]*=\s*)([^\n]+)" % re.escape(name))
        if not pattern.search(setup):
            error("%s: previewPresented names %r, which is not a `@State private var` with an initial value in setup"
                  % (entry_id, name))
            continue
        setup = pattern.sub(lambda m: "%sPreviewMode.presented ? %s : %s" % (m.group(1), value or "true", m.group(2)),
                            setup, count=1)
    return setup


def example_files(entries):
    """Two Swift files per family, so files stay small and compile in parallel.

    The stable one imports MonarchUI plainly. The experimental one imports it with
    `@_spi(Experimental)`, so a stable example cannot use an experimental symbol:
    it would not compile.
    """
    files = {}
    families = {}
    for entry in entries:
        for index, example in enumerate(entry["examples"]):
            key = (family_folder(entry["family"]), is_experimental_example(entry, example))
            families.setdefault(key, []).append((entry, index, example))
    for family, experimental in sorted(families):
        imports = {"MonarchTokens", "MonarchUI", "SwiftUI"}
        cases, structs = [], []
        for entry, index, example in families[(family, experimental)]:
            imports.update(example.get("imports", []))
            type_name = "%sExample%d" % (pascal(entry["id"]), index)
            presented = example.get("previewPresented", [])
            opens_menu = bool(example.get("previewMenu"))
            taps = bool(example.get("previewTap"))
            action = example.get("previewAction")
            flags = ""
            if presented or opens_menu or taps or example.get("previewScreen"):
                flags = ", presented: true" + (", opensMenu: true" if opens_menu else "") + (", taps: true" if taps else "")
            if action:
                flags += ", acts: true"
            cases.append("        InventoryExample(id: %s, title: %s%s) { AnyView(%s()) },"
                         % (swift_string(entry["id"]), swift_string(example["title"]), flags, type_name))
            setup_text = start_presented(entry["id"], example.get("setup", ""), presented)
            setup = indent(setup_text, 4) + "\n\n" if setup_text else ""
            if action:
                # The preview host runs the example's own action once (a toast after a delete, a result after a save).
                body = ("        Group {\n%s\n        }\n        .task {\n            guard PreviewMode.presented else { return }\n"
                        "            try? await Task.sleep(for: .milliseconds(400))\n%s\n        }"
                        % (indent(example["code"], 12), indent(action, 12)))
            else:
                body = indent(example["code"], 8)
            structs.append(
                "/// %s: %s\nprivate struct %s: View {\n%s    var body: some View {\n%s\n    }\n}\n"
                % (entry["id"], example["title"], type_name, setup, body))
        suffix = "Experimental" if experimental else ""
        lower = family[:1].lower() + family[1:] + suffix
        lines = ["%simport %s\n" % ("@_spi(Experimental) " if experimental and name == "MonarchUI" else "", name)
                 for name in sorted(imports)]
        files["Examples/%s%sExamples.generated.swift" % (family, suffix)] = (
            HEADER + "// Source: the %sexamples of the inventory files in the %s family.\n\n"
            % ("experimental " if experimental else "", family)
            + "".join(lines)
            + "\nextension InventoryExamples {\n    static let %s: [InventoryExample] = [\n%s\n    ]\n}\n\n"
            % (lower, "\n".join(cases))
            + "\n".join(structs))
    members = sorted({family[:1].lower() + family[1:] + ("Experimental" if experimental else "")
                      for family, experimental in families})
    joined = " + ".join(members) if members else "[]"
    files["Examples/InventoryExamples.generated.swift"] = (
        HEADER + "\n/// Every compiled example of every inventory file.\nenum InventoryExamples {\n"
        + "    /// The examples of one component keep the order of its inventory file, whichever file they compile in\n"
        + "    /// (a stable and an experimental example of one id sit in different files), so the first one is the primary.\n"
        + "    static let all: [InventoryExample] = {\n        let order = [\n"
        + "".join("            %s,\n" % swift_string(e["id"] + "|" + x["title"]) for e in entries for x in e["examples"])
        + "        ]\n        var rank: [String: Int] = [:]\n"
        + "        for (index, key) in order.enumerated() where rank[key] == nil { rank[key] = index }\n"
        + "        let unsorted: [InventoryExample] = %s\n" % joined
        + "        return unsorted.enumerated().sorted { left, right in\n"
        + "            let a = rank[left.element.id + \"|\" + left.element.title] ?? Int.max\n"
        + "            let b = rank[right.element.id + \"|\" + right.element.title] ?? Int.max\n"
        + "            return a == b ? left.offset < right.offset : a < b\n        }.map(\\.element)\n    }()\n}\n")
    return files


FIXTURES = re.compile(r"^(?:private |fileprivate )?enum\s+(\w+)\s*:\s*ComponentFixtures\s*\{", re.MULTILINE)
FIXTURE_ID = re.compile(r'static\s+let\s+id\s*=\s*"([^"]+)"')


def swift_files(directory):
    for folder, _, names in sorted(os.walk(directory)):
        if os.sep + "Generated" in folder + os.sep:
            continue
        for name in sorted(names):
            if name.endswith(".swift"):
                yield os.path.join(folder, name)


def scan_fixtures(ids):
    found = []
    for path in swift_files(TESTS):
        text = read(path)
        for match in FIXTURES.finditer(text):
            where = os.path.relpath(path, ROOT)
            fixture_id = FIXTURE_ID.search(text, match.end())
            if not fixture_id:
                error('%s: %s needs `static let id = "<inventory id>"`' % (where, match.group(1)))
                continue
            if fixture_id.group(1) not in ids:
                error("%s: %s has id %r, but inventory/%s.json does not exist"
                      % (where, match.group(1), fixture_id.group(1), fixture_id.group(1)))
            found.append((match.group(1), fixture_id.group(1)))
    names = [name for name, _ in found]
    for name in sorted(set(names)):
        if names.count(name) > 1:
            error("%s is declared more than once" % name)
    return sorted(found)


def fixture_registry(fixtures):
    lines = "\n".join("        FixtureSet(%s.self)," % name for name, _ in fixtures)
    return (HEADER + "// Source: every `enum …: ComponentFixtures` under Tests/MonarchUITests.\n\n"
            "/// The fixtures of every component, for the matrix test.\nenum FixtureRegistry {\n"
            "    static let all: [FixtureSet] = [\n%s\n    ]\n}\n" % lines)


PAGE = re.compile(r"^struct\s+(\w+)\s*:\s*CataloguePage\s*\{", re.MULTILINE)


def scan_pages():
    families = {}
    sections = os.path.join(SAMPLE, "Sections")
    for path in swift_files(sections):
        relative = os.path.relpath(path, sections).split(os.sep)
        where = os.path.relpath(path, ROOT)
        if len(relative) != 2:
            error("%s: sample sections live at Sample/Sources/Sections/<Family>/<Name>Section.swift" % where)
            continue
        for match in PAGE.finditer(read(path)):
            if match.group(1) + ".swift" != relative[1]:
                error("%s: the file must be named after %s" % (where, match.group(1)))
            families.setdefault(relative[0], []).append(match.group(1))
    return families


def catalogue_registry(families):
    blocks = []
    for family in sorted(families):
        pages = "\n".join("                CatalogueEntry(%s.self)," % name for name in sorted(families[family]))
        blocks.append("        CatalogueFamily(\n            name: %s,\n            entries: [\n%s\n            ]\n        ),"
                      % (swift_string(re.sub(r"(?<!^)([A-Z])", r" \1", family)), pages))
    return (HEADER + "// Source: every `struct …: CataloguePage` under Sample/Sources/Sections/<Family>/.\n\n"
            "/// The families and pages of the catalogue.\n@MainActor\nenum CatalogueRegistry {\n"
            "    static let families: [CatalogueFamily] = [\n%s\n    ]\n}\n" % "\n".join(blocks))


PUBLIC_DECLARATION = re.compile(r"^((?:@[A-Za-z_]+(?:\([^)]*\))?\s+)*)(public|open)\b")
EXPERIMENTAL_MARK = "@_spi(Experimental)"


def check_experimental(entries):
    """Status and compiler marking agree (C-055).

    An experimental entry's top-level public declarations are all `@_spi(Experimental) public`; an
    available entry has none. A stable example may not use an experimental symbol unless it says
    `"experimental": true`, which compiles it with the SPI import.
    """
    experimental_names = set()
    for entry in entries:
        if entry["status"] != "experimental" or entry["coverage"] != "build":
            continue
        experimental_names.add(entry["name"])
        experimental_names.update(re.findall(r"\b(?:struct|enum|class|protocol|typealias|actor)\s+(Monarch\w+)",
                                             " ".join(entry["api"])))
        folder = os.path.join(SOURCES, "Components", family_folder(entry["family"]), entry["name"])
        marked = 0
        files = list(swift_files(folder)) if os.path.isdir(folder) else []
        own = set()
        for path in files:
            own.update(re.findall(r"@_spi\(Experimental\)\s+public\s+(?:final\s+)?(?:struct|enum|class|protocol|typealias|actor)\s+(\w+)",
                                  read(path)))
        for path in files:
            lines = read(path).split("\n")
            extended = None
            for number, line in enumerate(lines, 1):
                if re.match(r"^\S", line):
                    extension = re.match(r"^(?:@\w+\s+)*(?:public\s+)?extension\s+([\w.]+)", line)
                    extended = extension.group(1) if extension else None
                member = extended is not None and extended not in own and re.match(
                    r"^    (?:@[A-Za-z_]+(?:\([^)]*\))?\s+)*public\b", line)
                match = PUBLIC_DECLARATION.match(line) or member
                if not match:
                    continue
                before = line
                for previous in reversed(lines[:number - 1]):
                    if previous.strip().startswith("@") and "public" not in previous:
                        before = previous + " " + before
                    else:
                        break
                if EXPERIMENTAL_MARK in before:
                    marked += 1
                else:
                    error("%s:%d: %s is experimental, so a public declaration needs %s (put it before `public`)"
                          % (os.path.relpath(path, ROOT), number, entry["id"], EXPERIMENTAL_MARK))
        if not marked:
            error("inventory/%s.json: status experimental, but %s declares no %s public API"
                  % (entry["id"], entry["name"], EXPERIMENTAL_MARK))
    for entry in entries:
        if entry["status"] == "experimental" or not entry["name"]:
            continue
        folder = os.path.join(SOURCES, "Components", family_folder(entry["family"]), entry["name"])
        for path in swift_files(folder) if os.path.isdir(folder) else []:
            if EXPERIMENTAL_MARK in read(path):
                error("%s: %s is %s, so it must not use %s; set status experimental in its inventory file"
                      % (os.path.relpath(path, ROOT), entry["id"], entry["status"], EXPERIMENTAL_MARK))
    for entry in entries:
        if entry["status"] == "experimental":
            continue
        for index, example in enumerate(entry["examples"]):
            if example.get("experimental"):
                continue
            text = example["code"] + "\n" + example.get("setup", "")
            used = sorted(name for name in experimental_names if re.search(r"\b%s\b" % re.escape(name), text))
            if used:
                error("inventory/%s.json: example %d of a %s entry uses the experimental %s; "
                      'set "experimental": true on that example' % (entry["id"], index, entry["status"], ", ".join(used)))


PARITY_FIXTURES = os.path.join(TESTS, "Generated", "Fixtures", "ParityFixtures.generated.swift")


def check_parity_fixtures(entries):
    """An example bound to a cross-platform fixture (CROSS-PLATFORM.md section 8) is the first one, and the
    fixture is generated. Its code is written by scripts/native/fixtures.mjs, whose --check is part of
    `npm run verify`; here only the binding is checked, so the iOS gate fails on a fixture that was never
    generated."""
    generated = read(PARITY_FIXTURES) if os.path.isfile(PARITY_FIXTURES) else ""
    for entry in entries:
        for index, example in enumerate(entry["examples"]):
            if "fixture" not in example:
                if "template" in example or "setupTemplate" in example:
                    error("inventory/%s.json: example %d has a template but no fixture" % (entry["id"], index))
                continue
            if index != 0:
                error("inventory/%s.json: only the first example binds a fixture" % entry["id"])
            if example["fixture"] != entry["id"] or "webExample" not in example or "template" not in example:
                error("inventory/%s.json: a bound example needs fixture %r, webExample and template"
                      % (entry["id"], entry["id"]))
            if 'id: "%s",' % example["fixture"] not in generated:
                error("inventory/%s.json: fixture %r is not in %s; run npm run native:fixtures"
                      % (entry["id"], example["fixture"], os.path.relpath(PARITY_FIXTURES, ROOT)))


def check_conventions(entries, fixtures):
    check_experimental(entries)
    check_parity_fixtures(entries)
    covered = {fixture_id for _, fixture_id in fixtures}
    for entry in entries:
        if entry["coverage"] in ("build", "style") and entry["id"] not in covered:
            error("inventory/%s.json: coverage %s needs fixtures: declare "
                  '`enum …: ComponentFixtures` with id "%s" in the component\'s test file'
                  % (entry["id"], entry["coverage"], entry["id"]))
    strings = os.path.join(SOURCES, "Resources", "en.lproj")
    for name in sorted(os.listdir(strings)):
        if name == "Localizable.strings":
            error("Resources/en.lproj/Localizable.strings: use one table per component, <TypeName>.strings")
        for key in re.findall(r'^"([^"]+)"\s*=', read(os.path.join(strings, name)), re.MULTILINE):
            if not key.startswith("monarch."):
                error("Resources/en.lproj/%s: key %r must start with monarch." % (name, key))


def sync(outputs, check):
    """Writes the outputs, or in check mode reports the stale ones. Removes generated files nothing produces."""
    stale = []
    for directory in {os.path.dirname(path) for path in outputs}:
        if os.path.isdir(directory):
            for name in os.listdir(directory):
                path = os.path.join(directory, name)
                if name.endswith(".generated.swift") and path not in outputs:
                    stale.append(path)
                    if not check:
                        os.remove(path)
    for path, content in sorted(outputs.items()):
        current = read(path) if os.path.isfile(path) else None
        if current != content:
            stale.append(path)
            if not check:
                os.makedirs(os.path.dirname(path), exist_ok=True)
                with open(path, "w", encoding="utf-8") as handle:
                    handle.write(content)
    return stale


def resolve(entries, name):
    """The inventory ids for a Swift type name, a title or an id."""
    wanted = name.lower()
    return sorted(entry["id"] for entry in entries
                  if wanted in (entry["id"].lower(), (entry["name"] or "").lower(), entry["title"].lower()))


def component_fixtures(entries, name):
    """(enum name, path) of every fixtures enum that belongs to the component."""
    ids = set(resolve(entries, name))
    found = []
    for path in swift_files(TESTS):
        text = read(path)
        for match in FIXTURES.finditer(text):
            fixture_id = FIXTURE_ID.search(text, match.end())
            if fixture_id and fixture_id.group(1) in ids:
                found.append((match.group(1), path))
    return found


def component_suites(entries, name):
    """<Name>Fixtures is declared beside the suite <Name>Tests."""
    return sorted({re.sub(r"Fixtures$", "", enum) + "Tests" for enum, _ in component_fixtures(entries, name)})


def component_files(entries, name):
    ids = resolve(entries, name)
    paths = {path for _, path in component_fixtures(entries, name)}
    for entry in entries:
        if entry["id"] not in ids:
            continue
        candidates = [entry["name"] or "", pascal(entry["id"]), pascal(entry["title"])]
        family = family_folder(entry["family"])
        folder = os.path.join(SOURCES, "Components", family, entry["name"] or "")
        if entry["name"] and os.path.isdir(folder):
            paths.update(swift_files(folder))
        for candidate in candidates:
            page = os.path.join(SAMPLE, "Sections", family, candidate + "Section.swift")
            if candidate and os.path.isfile(page):
                paths.add(page)
    return sorted(os.path.relpath(path, ROOT) for path in paths)


def parity_report(entries):
    path = os.path.join(os.path.dirname(ROOT), "parity.json")
    if not os.path.isfile(path):
        print("parity: %s not found; nothing to compare" % path)
        return
    plan = {item["id"]: item for item in json.loads(read(path))["components"]}
    have = {entry["id"]: entry for entry in entries}
    print("parity: %d of %d planned ids have an inventory file" % (len(set(plan) & set(have)), len(plan)))
    for entry_id in sorted(set(have) - set(plan)):
        print("parity: %s is not in parity.json (family %s)" % (entry_id, have[entry_id]["family"]))
    for entry_id in sorted(set(plan) & set(have)):
        planned, entry = plan[entry_id]["ios"], have[entry_id]
        for field, actual in (("coverage", entry["coverage"]), ("name", entry["name"])):
            if planned.get(field) != actual:
                print("parity: %s: %s is %r in the inventory and %r in parity.json"
                      % (entry_id, field, actual, planned.get(field)))
        if plan[entry_id]["family"] != entry["family"]:
            print("parity: %s: family is %r in the inventory and %r in parity.json"
                  % (entry_id, entry["family"], plan[entry_id]["family"]))


def main():
    arguments = sys.argv[1:]
    entries = load_inventory()
    if "--resolve" in arguments:
        ids = resolve(entries, arguments[arguments.index("--resolve") + 1])
        if not ids:
            sys.exit("generate: no inventory entry has that id, name or title")
        print(",".join(ids))
        return
    for flag, function in (("--suites", component_suites), ("--files", component_files)):
        if flag in arguments:
            print("\n".join(function(entries, arguments[arguments.index(flag) + 1])))
            return
    fixtures = scan_fixtures({entry["id"] for entry in entries})
    pages = scan_pages()
    check_conventions(entries, fixtures)
    if errors:
        for message in errors:
            print("generate: " + message, file=sys.stderr)
        sys.exit("generate: %d problem(s)" % len(errors))
    if "--parity" in arguments:
        parity_report(entries)
        return

    generated = os.path.join(TESTS, "Generated")
    outputs = {os.path.join(ROOT, "components.json"): components_json(entries)}
    for name, content in example_files(entries).items():
        outputs[os.path.join(generated, name)] = content
    outputs[os.path.join(generated, "FixtureRegistry.generated.swift")] = fixture_registry(fixtures)
    outputs[os.path.join(SAMPLE, "Generated", "CatalogueRegistry.generated.swift")] = catalogue_registry(pages)

    check = "--check" in arguments
    stale = sync(outputs, check)
    summary = "%d inventory entries, %d examples, %d fixture sets, %d sample pages" % (
        len(entries), sum(len(entry["examples"]) for entry in entries), len(fixtures),
        sum(len(names) for names in pages.values()))
    if check and stale:
        for path in stale:
            print("generate: stale: " + os.path.relpath(path, ROOT), file=sys.stderr)
        sys.exit("generate: run Scripts/generate.py")
    print("generate: %s; %s" % (summary, "up to date" if check or not stale else "%d file(s) written" % len(stale)))


if __name__ == "__main__":
    main()
