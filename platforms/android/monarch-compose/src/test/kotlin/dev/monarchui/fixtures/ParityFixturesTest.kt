package dev.monarchui.fixtures

import androidx.compose.ui.semantics.SemanticsNode
import androidx.compose.ui.semantics.SemanticsProperties
import androidx.compose.ui.semantics.getOrNull
import androidx.compose.ui.test.hasClickAction
import androidx.compose.ui.test.hasContentDescription
import androidx.compose.ui.test.hasText
import androidx.compose.ui.test.junit4.v2.createComposeRule
import androidx.compose.ui.test.isRoot
import dev.monarchui.generated.examples.AllInventoryExamples
import dev.monarchui.testing.setMonarchContent
import org.junit.Rule
import org.junit.runner.RunWith
import org.robolectric.ParameterizedRobolectricTestRunner
import org.robolectric.annotation.Config
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertTrue

/**
 * The Android side of the cross-platform scenario fixtures (CROSS-PLATFORM.md section 8, item 4). Each fixture
 * ([ParityFixtures], generated by `scripts/native/fixtures.mjs`) is the scenario of a web primary example. The
 * first inventory example of the same id is written from it; this renders that example and reads the semantics
 * tree: every text of the fixture is shown, in the web's reading order, and every web button is a button with
 * the same label.
 */
@RunWith(ParameterizedRobolectricTestRunner::class)
// A tall window, so a lazy list or a scrolling recipe composes everything the web page shows.
@Config(qualifiers = "+w392dp-h4000dp")
class ParityFixturesTest(private val id: String) {
    @get:Rule
    val rule = createComposeRule()

    @Test
    fun thePrimaryExampleShowsTheFixture() {
        val failure = runCatching { checkPrimaryExample() }.exceptionOrNull()
        val known = KnownGaps.contains(id)
        // The worklist for the fixes: what is still missing, per id (build/parity-gaps/<id>.txt).
        java.io.File("build/parity-gaps").apply { mkdirs() }.resolve("$id.txt").apply {
            if (failure == null) delete() else writeText(failure.message.orEmpty())
        }
        // The backlog only shrinks: a new gap and a gap that is closed but still listed both fail.
        assertTrue(failure == null || failure is AssertionError, "$id: ${failure?.message}")
        assertTrue(
            known != (failure == null),
            failure?.message ?: "$id now shows its fixture: remove it from parity-fixtures-baseline.txt",
        )
    }

    @Suppress("CyclomaticComplexMethod")
    private fun checkPrimaryExample() {
        val fixture = ParityFixtures.all.single { it.id == id }
        val primary = AllInventoryExamples.first { it.id == id }
        assertEquals(fixture.exampleTitle, primary.title, "$id: the fixture is the first inventory example")
        rule.setMonarchContent { primary.content() }

        // What is on screen, in reading order, and what a screen reader reads for a control or a picture. A name
        // read for TalkBack has no place in the visual order, so it matches wherever it is.
        val texts = mutableListOf<String>()
        val names = mutableListOf<String>()
        fun walk(node: SemanticsNode) {
            node.config.getOrNull(SemanticsProperties.Text)?.forEach { texts += it.text }
            node.config.getOrNull(SemanticsProperties.EditableText)?.let { texts += it.text }
            node.config.getOrNull(SemanticsProperties.ContentDescription)?.forEach { names += it }
            node.children.forEach(::walk)
        }
        // A dialog, sheet or menu is a window of its own, so there can be several roots: read them all.
        rule.onAllNodes(isRoot(), useUnmergedTree = true).fetchSemanticsNodes().forEach(::walk)
        val shown = (texts + names).joinToString(" | ")
        // The reading order of the semantics tree is not the visual order (a heading is read after its section, a
        // description before its control); the visual order is checked by eye on the review sheets. Here every text
        // of the fixture must be shown somewhere, as its own text or inside a longer one.
        val everything = (texts + names).map { it.flat() }
        // Neighbouring texts read together ("£120.00" and "/ month" for "£120.00 / month").
        val joined = everything.joinToString(" ")
        val excused = excusedTexts()
        val missing = mutableListOf<String>()
        for (text in fixture.texts.filterNot { it.isKeyboardOrPointerHint() || it in excused }) {
            val want = text.flat()
            // The same words in another order inside one text ("Revenue: 2310" for "2310 Revenue") count; a word that
            // is missing, or spread over several texts, does not.
            val shownSomewhere = want.isEmpty() || joined.contains(want) || wordsIn(want, everything)
            if (!shownSomewhere) missing += "text \"$text\""
        }
        val words = everything.joinToString(" ").flat()
        for (action in fixture.actions.filter { it.label.isNotBlank() && it.label !in excused }) {
            val named = hasText(action.label, substring = true) or
                hasContentDescription(action.label, substring = true)
            val buttons = rule.onAllNodes(hasClickAction() and named, useUnmergedTree = false).fetchSemanticsNodes()
            // The web label of a button is often its text and hidden text run together ("CopyCopied", "👍4"); it
            // is satisfied when every word of it is on screen.
            val word = Regex("[\\p{Lu}]+(?![\\p{Ll}])|\\p{Lu}?\\p{Ll}+|\\p{N}+")
            // "Copied" is the state read after a copy (the state description), not a label of the idle button.
            val tokens = word.findAll(action.label).map { it.value }.filter { it != "Copied" }.toList()
            val allThere = tokens.isNotEmpty() && tokens.all { words.contains(it) }
            if (buttons.isEmpty() && !allThere) missing += "button \"${action.label}\""
        }
        assertTrue(missing.isEmpty(), "$id: missing ${missing.joinToString(" ;; ")}\nshown: $shown")
    }

    private val wordPattern = Regex("[\\p{L}\\p{N}][\\p{L}\\p{N}.,:'’%$€£₹+−-]*")

    private fun wordsOf(text: String): List<String> =
        wordPattern.findAll(text).map { it.value.trim('.', ',', ':') }.toList()

    private fun wordsIn(text: String, shown: List<String>): Boolean {
        val wanted = wordsOf(text)
        return wanted.isNotEmpty() && shown.any { wordsOf(it).containsAll(wanted) }
    }

    /** Texts the inventory excuses with a reason: `parityExceptions` of rule `fixture-text`, texts in `paths`. */
    private fun excusedTexts(): Set<String> {
        val file = java.io.File(System.getProperty("monarch.rootDir") ?: ".", "inventory/$id.json")
        if (!file.exists()) return emptySet()
        val exceptions = org.json.JSONObject(file.readText()).optJSONArray("parityExceptions") ?: return emptySet()
        return (0 until exceptions.length()).map { exceptions.getJSONObject(it) }
            .filter { it.optString("rule") == "fixture-text" }
            .flatMap { x -> x.optJSONArray("paths")?.let { a -> (0 until a.length()).map(a::getString) }.orEmpty() }
            .toSet()
    }

    private fun String.isKeyboardOrPointerHint(): Boolean =
        Regex("(Shift|Ctrl|Alt|Cmd|⌘|Enter|Escape|Tab)\\s*\\+|[Rr]ight-click|press (Enter|M|J|K|Escape)\\b")
            .containsMatchIn(this)

    /** The text on one line with single spaces, so a line break or a no-break space does not hide a match. */
    // jsdom writes short numbers as "£1.2m" where a browser has "£1.2M": compare the suffix in capitals.
    private fun String.flat(): String = replace('\u00A0', ' ').replace(Regex("\\s+"), " ").trim()
        .replace(Regex("(\\d)([kmbt])(?!\\p{L})")) { it.groupValues[1] + it.groupValues[2].uppercase() }

    companion object {
        /** The ids in the backlog (`src/test/resources/parity-fixtures-baseline.txt`). */
        private val KnownGaps: Set<String> by lazy {
            checkNotNull(ParityFixturesTest::class.java.getResourceAsStream("/parity-fixtures-baseline.txt")) {
                "parity-fixtures-baseline.txt is missing"
            }.bufferedReader().readLines().filter { it.isNotBlank() && !it.startsWith("#") }
                .map { it.substringBefore(' ') }.toSet()
        }

        @JvmStatic
        @ParameterizedRobolectricTestRunner.Parameters(name = "{0}")
        fun ids(): List<Array<String>> = ParityFixtures.all.map { arrayOf(it.id) }
    }
}
