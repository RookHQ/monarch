package com.rookhq.monarch.components.collaboration.calltile

/** The size of a `MonarchCallTile`. */
public enum class MonarchCallTileSize {
    /** The filmstrip size: a 32dp avatar and no Pin or full-screen buttons. */
    Sm,

    /** The grid size, with a 40dp avatar. The default. */
    Md,

    /** The main spot, with a 40dp avatar. */
    Lg,
}
