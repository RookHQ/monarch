package com.rookhq.monarch.components.identity.signinwithrookbutton

/**
 * The size of a `MonarchSignInWithRookButton`. The size sets the visible
 * height; the touch target is at least 48dp at every size.
 */
public enum class MonarchSignInWithRookButtonSize {
    /** 32dp high, with a 16dp mark. */
    Sm,

    /** 40dp high, with a 20dp mark. The default. */
    Md,

    /** 48dp high, with a 24dp mark. */
    Lg,
}
