package com.rookhq.monarch.components.datadisplay.statusdot

/** The size of a `MonarchStatusDot`. The same names exist on every platform. */
public enum class MonarchStatusDotSize {
    /** An 8dp dot with caption text. For table cells, lists and other small text. The default. */
    Sm,

    /** A 10dp dot with label-sized text. Next to body text. */
    Md,
}
