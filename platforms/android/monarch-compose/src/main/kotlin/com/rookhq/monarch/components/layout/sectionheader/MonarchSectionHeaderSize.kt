package com.rookhq.monarch.components.layout.sectionheader

/** The size of a `MonarchSectionHeader`. The same names exist on every platform. */
public enum class MonarchSectionHeaderSize {
    /** A 14sp semibold title, for dashboard sections and headers inside a card. The default. */
    Sm,

    /** A 16sp semibold title, for the sections of a screen. */
    Md,
}
