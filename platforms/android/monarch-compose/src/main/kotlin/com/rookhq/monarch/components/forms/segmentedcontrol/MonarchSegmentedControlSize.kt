package com.rookhq.monarch.components.forms.segmentedcontrol

/** The size of a `MonarchSegmentedControl`: the visible height of the track, as the web's `sm`, `md` and `lg`. */
public enum class MonarchSegmentedControlSize {
    /** A 32dp track and 12sp text, for dense toolbars. */
    Sm,

    /** A 36dp track and 14sp text. The default. */
    Md,

    /** A 40dp track and 14sp text with wider segments. */
    Lg,
}
