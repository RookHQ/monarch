private typealias Tokens = MonarchAiImageGenerationTokens

/**
 * Images generated by AI, as a grid of variations: placeholders while they
 * generate, previews with progress while they refine, then each image with
 * a required alt text field and "Use image" and "More like this" actions.
 *
 * Built by Monarch from rows of equal cells (as many columns of at least
 * 160dp as fit, scaled with the font size), `MonarchSkeleton` placeholders,
 * a `MonarchProgress` bar, a `MonarchTextField` per image and small
 * `MonarchButton`s. It is not a lazy grid, because a few variations sit in a
 * conversation that already scrolls. Monarch loads no images: pass each one
 * as a `Painter`. The component is controlled: alt text edits and choices
 * go to the callbacks and come back in [images] and [selection].
 *
 * TalkBack reads the group by its label; the status line is text and the
 * progress bar is hidden, because the line carries the percentage.
 * Completion is announced once through a polite live region. Each image is
 * read by its alt text, or "Generated image n" while that is empty; each
 * alt field has its own label and error. The action buttons are named with
 * the image's position, and "Use image" is selected on the chosen image,
 * which also has a thicker ring and a "Selected" mark.
 *
 * @param images the images, or their slots while generating, in order.
 * @param status where the generation is.
 * @param onAltChange called with an image's id and its new alt text as the person types.
 * @param modifier the modifier of the group.
 * @param progress overall progress from 0 to 1, shown while generating. `null` when unknown.
 * @param selection the id of the chosen image, or `null`.
 * @param onSelect adds "Use image" to each finished image; called with its id.
 * @param onVariations adds "More like this" to each finished image; called with its id.
 * @param onRetry adds a retry button in the error state.
 * @param error replaces the built-in error message.
 * @param labels replacements for the built-in strings.
 */
@Composable
public fun MonarchAiImageGeneration(
    images: List<MonarchAiGeneratedImage>,
    status: MonarchAiImageGenerationStatus,
    onAltChange: (id: String, alt: String) -> Unit,
    modifier: Modifier = Modifier,
    progress: Float? = null,
    selection: String? = null,
    onSelect: ((String) -> Unit)? = null,
    onVariations: ((String) -> Unit)? = null,
    onRetry: (() -> Unit)? = null,
    error: String? = null,
    labels: MonarchAiImageGenerationLabels = MonarchAiImageGenerationLabels(),
) {
    val strings = rememberStrings(labels, images.size)
    val name = monarchString(labels.label, R.string.monarch_aiimagegeneration_label)
    Column(
        modifier = modifier
            .fillMaxWidth()
            .semantics {
                isTraversalGroup = true
                contentDescription = name
            },
        verticalArrangement = Arrangement.spacedBy(Tokens.SectionGap),
    ) {
        StatusLine(status, progress, error, onRetry, labels, strings)
        Completion(status, strings.announceDone)
        if (images.isNotEmpty()) {
            Grid(images.size) { index ->
                ImageItem(
                    image = images[index],
                    position = index + 1,
                    status = status,
                    selection = selection,
                    onAltChange = onAltChange,
                    onSelect = onSelect,
                    onVariations = onVariations,
                    labels = labels,
                )
            }
        }
    }
}

/** The strings that depend on the number of images. */
private class CountStrings(val done: String, val announceDone: String)

@Composable
private fun rememberStrings(labels: MonarchAiImageGenerationLabels, count: Int): CountStrings = CountStrings(
    done = labels.done?.invoke(count)
        ?: pluralStringResource(R.plurals.monarch_aiimagegeneration_done, count, count),
    announceDone = labels.announceDone?.invoke(count)
        ?: pluralStringResource(R.plurals.monarch_aiimagegeneration_announce_done, count, count),
)

@Composable
private fun StatusLine(
    status: MonarchAiImageGenerationStatus,
    progress: Float?,
    error: String?,
    onRetry: (() -> Unit)?,
    labels: MonarchAiImageGenerationLabels,
    strings: CountStrings,
) {
    val locale = LocalConfiguration.current.locales[0]
    val percent = Tokens.percent(progress, locale)
    val text = when (status) {
        MonarchAiImageGenerationStatus.Pending -> labels.pending?.invoke(percent) ?: generatingText(
            percent,
            R.string.monarch_aiimagegeneration_pending,
            R.string.monarch_aiimagegeneration_pending_progress,
        )
        MonarchAiImageGenerationStatus.Progressive -> labels.progressive?.invoke(percent) ?: generatingText(
            percent,
            R.string.monarch_aiimagegeneration_progressive,
            R.string.monarch_aiimagegeneration_progressive_progress,
        )
        MonarchAiImageGenerationStatus.Done -> strings.done
        MonarchAiImageGenerationStatus.Error -> null
    }
    if (text != null) {
        Text(text = text, style = MonarchTheme.typography.caption, color = MonarchTheme.colors.textMuted)
    } else {
        val message = error ?: monarchString(labels.error, R.string.monarch_aiimagegeneration_error)
        if (onRetry != null) {
            MonarchInlineErrorRetry(
                message = message,
                onRetry = onRetry,
                variant = MonarchInlineErrorRetryVariant.Banner,
                retryLabel = monarchString(labels.retry, R.string.monarch_aiimagegeneration_retry),
            )
        } else {
            MonarchInlineNotice(message = message, tone = MonarchTone.Danger)
        }
    }
    val value = Tokens.clamped(progress)
    if (Tokens.generating(status) && value != null) {
        // Hidden: the status line above carries the percentage.
        MonarchProgress(modifier = Modifier.fillMaxWidth().clearAndSetSemantics { }, progress = value)
    }
}

@Composable
private fun generatingText(percent: String?, plain: Int, withPercent: Int): String =
    if (percent == null) stringResource(plain) else stringResource(withPercent, percent)

/** A polite live region that is always present and speaks once when generation finishes. */
@Composable
private fun Completion(status: MonarchAiImageGenerationStatus, text: String) {
    var previous by remember { mutableStateOf<MonarchAiImageGenerationStatus?>(null) }
    var announcement by remember { mutableStateOf("") }
    LaunchedEffect(status) {
        if (Tokens.announcesCompletion(previous, status)) {
            announcement = text
        } else if (status != MonarchAiImageGenerationStatus.Done) {
            announcement = ""
        }
        previous = status
    }
    MonarchLiveStatus(text = announcement.takeIf { it.isNotEmpty() }, visible = false)
}

@Composable
private fun Grid(count: Int, item: @Composable (Int) -> Unit) {
    val fontScale = LocalDensity.current.fontScale
    BoxWithConstraints(Modifier.fillMaxWidth()) {
        val columns = Tokens.columns(maxWidth, fontScale)
        Column(verticalArrangement = Arrangement.spacedBy(Tokens.GridGap)) {
            List(count) { it }.chunked(columns).forEach { row ->
                Row(horizontalArrangement = Arrangement.spacedBy(Tokens.GridGap)) {
                    row.forEach { index -> Box(Modifier.weight(1f)) { item(index) } }
                    // Empty cells keep the last row's images the width of the others.
                    repeat(columns - row.size) { Spacer(Modifier.weight(1f)) }
                }
            }
        }
    }
}

@OptIn(ExperimentalLayoutApi::class)
@Composable
private fun ImageItem(
    image: MonarchAiGeneratedImage,
    position: Int,
    status: MonarchAiImageGenerationStatus,
    selection: String?,
    onAltChange: (String, String) -> Unit,
    onSelect: ((String) -> Unit)?,
    onVariations: ((String) -> Unit)?,
    labels: MonarchAiImageGenerationLabels,
) {
    val selected = selection != null && selection == image.id
    val altLabel = labels.altLabel?.invoke(position)
        ?: stringResource(R.string.monarch_aiimagegeneration_alt_label, position)
    val altError = if (Tokens.altInvalid(image.alt, status)) {
        monarchString(labels.altRequired, R.string.monarch_aiimagegeneration_alt_required)
    } else {
        null
    }
    Column(verticalArrangement = Arrangement.spacedBy(Tokens.ItemGap)) {
        ImageSlot(image, Tokens.slot(image, status), selected, position, labels)
        MonarchTextField(
            value = image.alt,
            onValueChange = { onAltChange(image.id, it) },
            modifier = Modifier.fillMaxWidth(),
            label = altLabel,
            errorText = altError,
            enabled = status != MonarchAiImageGenerationStatus.Pending,
            singleLine = true,
            required = true,
        )
        if (Tokens.showsActions(image, status, onSelect != null, onVariations != null)) {
            FlowRow(horizontalArrangement = Arrangement.spacedBy(Tokens.ItemGap)) {
                if (onSelect != null) {
                    val spoken = labels.selectName?.invoke(position)
                        ?: stringResource(R.string.monarch_aiimagegeneration_select_name, position)
                    MonarchButton(
                        text = monarchString(labels.select, R.string.monarch_aiimagegeneration_select),
                        onClick = { onSelect(image.id) },
                        modifier = Modifier.semantics {
                            contentDescription = spoken
                            this.selected = selected
                        },
                        variant = if (selected) MonarchButtonVariant.Primary else MonarchButtonVariant.Secondary,
                        size = MonarchButtonSize.Sm,
                    )
                }
                if (onVariations != null) {
                    val spoken = labels.variationsName?.invoke(position)
                        ?: stringResource(R.string.monarch_aiimagegeneration_variations_name, position)
                    MonarchButton(
                        text = monarchString(labels.variations, R.string.monarch_aiimagegeneration_variations),
                        onClick = { onVariations(image.id) },
                        modifier = Modifier.semantics { contentDescription = spoken },
                        variant = MonarchButtonVariant.Ghost,
                        size = MonarchButtonSize.Sm,
                    )
                }
            }
        }
    }
}

@Composable
private fun ImageSlot(
    image: MonarchAiGeneratedImage,
    slot: Slot,
    selected: Boolean,
    position: Int,
    labels: MonarchAiImageGenerationLabels,
) {
    val colors = MonarchTheme.colors
    val shape = MonarchShapeDefaults.Control
    val name = image.alt.trim().ifEmpty {
        labels.imageName?.invoke(position) ?: stringResource(R.string.monarch_aiimagegeneration_image_name, position)
    }
    val shows = slot == Slot.Image || slot == Slot.Refining
    val unavailable = monarchString(labels.unavailable, R.string.monarch_aiimagegeneration_unavailable)
    Box(
        modifier = Modifier
            .fillMaxWidth()
            .aspectRatio(1f)
            .border(
                width = Tokens.ringWidth(selected, MonarchShapeDefaults.BorderWidth),
                color = Tokens.ringColor(selected, colors),
                shape = shape,
            )
            .then(
                // The placeholder hides its content, so the missing image is named here.
                if (slot == Slot.Unavailable) {
                    Modifier.semantics { contentDescription = unavailable }
                } else {
                    Modifier
                },
            ),
    ) {
        MonarchImage(
            painter = if (shows) image.image else null,
            contentDescription = name,
            modifier = Modifier
                .fillMaxSize()
                .then(if (slot == Slot.Refining) Modifier.blur(Tokens.RefiningBlur) else Modifier),
            shape = shape,
        ) {
            when (slot) {
                Slot.Placeholder -> MonarchSkeleton(Modifier.fillMaxSize().clearAndSetSemantics { })
                Slot.Unavailable -> Text(
                    text = unavailable,
                    modifier = Modifier.padding(Tokens.MarkPadding),
                    style = MonarchTheme.typography.caption,
                    color = colors.textMuted,
                    textAlign = TextAlign.Center,
                )
                else -> Unit
            }
        }
        if (selected) {
            // Hidden: "Use image" carries the selected state.
            Text(
                text = monarchString(labels.selected, R.string.monarch_aiimagegeneration_selected),
                modifier = Modifier
                    .align(Alignment.TopStart)
                    .padding(Tokens.MarkPadding)
                    .clearAndSetSemantics { }
                    .background(colors.aiSolid, MonarchShapeDefaults.Mark)
                    .padding(horizontal = Tokens.MarkInset * 2, vertical = Tokens.MarkInset / 2),
                style = MonarchTheme.typography.caption,
                color = colors.aiOnSolid,
            )
        }
    }
}
