package com.rookhq.monarch.components.charts.stackedproportionbar

/** The thickness of a `MonarchStackedProportionBar`. */
public enum class MonarchStackedProportionBarSize {
    /** 4dp, for table rows and tiles. */
    Sm,

    /** 8dp, the default. */
    Md,

    /** 12dp, for a bar that leads a card. */
    Lg,
}
