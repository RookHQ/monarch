package com.rookhq.monarch.components.geo.addressautocomplete

/** A field of the address form of a `MonarchAddressAutocomplete`, to attach an error to. */
public enum class MonarchAddressAutocompleteField {
    /** The first street line. */
    Line1,

    /** The second street line. */
    Line2,

    /** The city. */
    City,

    /** The state, province or region. */
    Region,

    /** The postal code. */
    PostalCode,

    /** The country. */
    Country,
}
