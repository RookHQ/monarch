package com.rookhq.monarch.components.typography.inlinecodestyle

/** The look of inline code. The same two names exist on every platform. */
public enum class MonarchInlineCodeVariant {
    /** The code typeface on the muted background. For code in running text. The default. */
    Subtle,

    /** The code typeface only. For code in dense places such as table cells. */
    Plain,
}
