package com.rookhq.monarch.components.datadisplay.metric

/** The size of a `MonarchMetric`. The same names exist on every platform. */
public enum class MonarchMetricSize {
    /** For dense rows and table footers. */
    Sm,

    /** The default. */
    Md,

    /** A headline figure. The change is drawn one size larger too. */
    Lg,
}
