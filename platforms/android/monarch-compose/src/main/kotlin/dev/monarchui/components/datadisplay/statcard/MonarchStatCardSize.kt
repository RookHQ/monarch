package dev.monarchui.components.datadisplay.statcard

/** The size of a `MonarchStatCard`. */
public enum class MonarchStatCardSize {
    /** Compact, for dense rows of cards: caption label, body-sized value, 12dp padding. */
    Sm,

    /** The default: label style, heading-sized value, 16dp padding. */
    Md,

    /** A hero figure: label style, display-sized value, 20dp padding. */
    Lg,
}
