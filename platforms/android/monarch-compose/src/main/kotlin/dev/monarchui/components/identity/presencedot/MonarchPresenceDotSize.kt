package dev.monarchui.components.identity.presencedot

/** The size of a `MonarchPresenceDot`. The dot grows with the font size setting. */
public enum class MonarchPresenceDotSize {
    /** An 8dp dot. For lists and avatars up to 24dp. */
    Sm,

    /** A 10dp dot. The default. */
    Md,

    /** A 12dp dot. For large avatars. */
    Lg,
}
