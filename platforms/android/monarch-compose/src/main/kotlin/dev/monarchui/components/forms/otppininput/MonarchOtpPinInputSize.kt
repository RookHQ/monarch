package dev.monarchui.components.forms.otppininput

/** The size of the cells of a `MonarchOtpPinInput`. Both are at least 48dp high, the touch target. */
public enum class MonarchOtpPinInputSize {
    /** Cells up to 48dp wide and 48dp high. */
    Md,

    /** Cells up to 64dp wide and 64dp high, with larger characters. */
    Lg,
}
