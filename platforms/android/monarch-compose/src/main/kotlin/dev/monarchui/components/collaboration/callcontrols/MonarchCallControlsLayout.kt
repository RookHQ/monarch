package dev.monarchui.components.collaboration.callcontrols

/** The stage layout offered in the More menu of `MonarchCallControls`. The same names exist on every platform. */
public enum class MonarchCallControlsLayout {
    /** The app chooses. */
    Automatic,

    /** Everyone in an even grid. */
    Grid,

    /** The active speaker large, the others small. */
    Speaker,
}
