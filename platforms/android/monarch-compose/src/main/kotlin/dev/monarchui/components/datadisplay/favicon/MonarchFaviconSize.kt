package dev.monarchui.components.datadisplay.favicon

/** The size of a `MonarchFavicon`. The same names exist on every platform. */
public enum class MonarchFaviconSize {
    /** 16dp. Beside caption or label text, in lists and tables. The default. */
    Sm,

    /** 24dp. Beside body text. */
    Md,

    /** 32dp. In a card header or a detail screen. */
    Lg,
}
