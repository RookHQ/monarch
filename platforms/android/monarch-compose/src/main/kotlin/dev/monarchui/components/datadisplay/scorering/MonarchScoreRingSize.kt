package dev.monarchui.components.datadisplay.scorering

/** The diameter of a `MonarchScoreRing` at the default font size. The same names exist on every platform. */
public enum class MonarchScoreRingSize {
    /** 48dp, for a row or a table cell. The maximum is not shown by default. */
    Sm,

    /** 80dp. The default. */
    Md,

    /** 120dp, for the main figure of a screen. */
    Lg,
}
