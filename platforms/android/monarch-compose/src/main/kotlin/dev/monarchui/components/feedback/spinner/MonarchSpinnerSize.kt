package dev.monarchui.components.feedback.spinner

/** The diameter of a `MonarchSpinner`. The stroke is 2dp at every size. */
public enum class MonarchSpinnerSize {
    /** 14dp. Inside a small button or a dense row. */
    Sm,

    /** 16dp. The default: next to a label or inside a button. */
    Md,

    /** 24dp. On its own in a card or a loading area. */
    Lg,
}
