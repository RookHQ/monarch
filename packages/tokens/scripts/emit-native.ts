interface Rgba {
  /** 0xRRGGBB */
  readonly rgb: number;
  readonly alpha: number;
}
interface Shadow {
  readonly color: Rgba;
  readonly x: number;
  readonly y: number;
  readonly blur: number;
  readonly spread: number;
}
type Entry<T> = readonly [name: string, value: T];

function at<T>(list: readonly T[], i: number): T {
  const item = list[i];
  if (item === undefined) throw new Error(`No item at ${i}`);
  return item;
}
const cap = (s: string) => s.charAt(0).toUpperCase() + s.slice(1);
/** `solid-hover` → `solidHover`, `bg.canvas` → `bgCanvas`, `data.1` → `data1`. */
const camel = (s: string) =>
  s
    .split(/[-.]/)
    .map((part, i) => (i === 0 ? part : cap(part)))
    .join('');
/** Identifiers cannot start with a digit: `2xl` → `xl2`, `2xs` → `xs2`. */
const ident = (key: string) => camel(key.replace(/^(\d+)(.+)$/, '$2$1'));
/** Keys of a numeric scale: `0.5` → `space0_5`, `px` → `px`. */
const stepName = (prefix: string, key: string) =>
  /^\d/.test(key) ? `${prefix}${key.replace(/[.-]/g, '_')}` : camel(key);

const rgbaOfHsl = (c: Hsl): Rgba => ({ rgb: parseInt(toHex(c).slice(1), 16), alpha: 1 });
/** A derived colour as the CSS prints it (channels rounded to one decimal), so native equals the web. */
const rgbaOfCss = (c: Hsl): Rgba => {
  const parsed = parseCssHsl(toCss(c));
  if (!parsed) throw new Error(`Cannot read ${toCss(c)}`);
  return rgbaOfHsl(parsed.color);
};
const rgbaOfDtcg = (c: DtcgColor): Rgba => ({
  rgb: parseInt(c.hex.slice(1), 16),
  alpha: c.alpha ?? 1,
});

/** CSS length in dp / pt. */
function points(value: string): number {
  if (value === '0') return 0;
  const m = /^(-?[\d.]+)(rem|px)$/.exec(value);
  if (!m) throw new Error(`Unsupported length ${value}`);
  return Math.round(Number(m[1]) * (m[2] === 'rem' ? 16 : 1) * 1000) / 1000;
}
const entries = <V, T>(
  o: Readonly<Record<string, V>>,
  name: (k: string) => string,
  v: (x: V) => T,
) => Object.entries(o).map(([k, x]): Entry<T> => [name(k), v(x)]);
const colorRamp = (o: Readonly<Record<string | number, Hsl>>, prefix: string) =>
  entries(o as Record<string, Hsl>, (k) => stepName(prefix, k), rgbaOfHsl);
const flatRamps = (o: Readonly<Record<string, Readonly<Record<string | number, Hsl>>>>) =>
  Object.entries(o).flatMap(([name, ramp]) => colorRamp(ramp, name));

const cubicBezier = (v: string) => {
  const m = /^cubic-bezier\(([^)]+)\)$/.exec(v);
  if (!m) throw new Error(`Unsupported easing ${v}`);
  return (m[1] ?? '').split(',').map((n) => Number(n.trim())) as [number, number, number, number];
};

