/* Kotlin ----------------------------------------------------------- */

const ktColor = (c: Rgba) =>
  `0x${Math.round(c.alpha * 255)
    .toString(16)
    .toUpperCase()
    .padStart(2, '0')}${hex6(c.rgb)}L`;
const ktFloat = (n: number) => `${num(n)}f`;

function kotlin(): string {
  const o: string[] = [];
  const obj = (name: string, doc: string, lines: string[]) => {
    o.push(
      `    /** ${doc} */`,
      `    public object ${name} {`,
      ...lines.map((l) => `        ${l}`),
      '    }',
      '',
    );
  };
  const consts = <T>(type: string, list: Entry<T>[], print: (v: T) => string) =>
    list.map(([n, v]) => `public const val ${n}: ${type} = ${print(v)}`);
  const ktShadow = (layers: Shadow[]) =>
    `listOf(${layers
      .map(
        (l) =>
          `MonarchShadowLayer(${ktColor(l.color)}, ${ktFloat(l.x)}, ${ktFloat(l.y)}, ${ktFloat(l.blur)}, ${ktFloat(l.spread)})`,
      )
      .join(', ')})`;
  const accentRoles = ACCENT_ROLES.map(camel);
  /** The body of withAccent / withAi: copy `colors`, taking the follower roles from `a`. */
  const ktReplace = (by: (t: Theme) => ReadonlyMap<string, string>) => {
    const differs = themeList.some((t) => [...by(t)].join() !== [...by(baseTheme)].join());
    const build = (t: Theme, indent: string) =>
      roleNames.map((r) => {
        const f = by(t).get(r);
        return `${indent}${r} = ${f ? `a.${f}` : `c.${r}`},`;
      });
    return [
      '        val c = colors',
      ...(differs
        ? [
            '        val next = when (id) {',
            ...[...themeList.slice(1), baseTheme].flatMap((t, i) => [
              `            ${i === themeList.length - 1 ? 'else' : `"${t.id}"`} -> MonarchColorTokens(`,
              ...build(t, '                '),
              '            )',
            ]),
            '        }',
          ]
        : [
            '        val next = MonarchColorTokens(',
            ...build(baseTheme, '            '),
            '        )',
          ]),
      '        return MonarchThemeTokens(id, isDark, isHighContrast, focusRingWidth, next, shadows)',
    ];
  };

  o.push(
    `// ${HEADER}`,
    '@file:Suppress("MagicNumber", "LongParameterList", "MaxLineLength")',
    '',
    'package dev.monarchui.tokens',
    '',
    '/** One layer of a shadow. Colour is ARGB; lengths are dp. */',
    'public class MonarchShadowLayer(',
    '    public val color: Long,',
    '    public val offsetX: Float,',
    '    public val offsetY: Float,',
    '    public val blur: Float,',
    '    public val spread: Float,',
    ')',
    '',
    '/** The five elevation levels of a theme, each a list of layers. */',
    'public class MonarchShadowTokens(',
    ...SHADOW_SIZES.map((s) => `    public val ${s}: List<MonarchShadowLayer>,`),
    ')',
    '',
    '/** A cubic Bézier easing curve. */',
    'public class MonarchCubicBezier(',
    '    public val x1: Float,',
    '    public val y1: Float,',
    '    public val x2: Float,',
    '    public val y2: Float,',
    ')',
    '',
    '/** The accent roles of one theme. Colours are ARGB. */',
    'public class MonarchAccentScale(',
    ...accentRoles.map((r) => `    public val ${r}: Long,`),
    ')',
    '',
    '/** A brand accent with a scale for each of the four themes. */',
    'public class MonarchAccent(',
    '    public val id: String,',
    '    public val label: String,',
    ...themeList.map((t) => `    public val ${t.name}: MonarchAccentScale,`),
    ') {',
    '    /** The scale for a theme id (`light`, `dark`, `hc-light`, `hc-dark`). */',
    '    public fun scale(themeId: String): MonarchAccentScale = when (themeId) {',
    ...themeList.slice(1).map((t) => `        "${t.id}" -> ${t.name}`),
    `        else -> ${baseTheme.name}`,
    '    }',
    '}',
    '',
    '/** Every semantic colour of one theme. Colours are ARGB. */',
    'public class MonarchColorTokens(',
    ...roleNames.map((r) => `    public val ${r}: Long,`),
    ')',
    '',
    '/** One theme: its colours, shadows and focus ring width (dp). */',
    'public class MonarchThemeTokens(',
    '    public val id: String,',
    '    public val isDark: Boolean,',
    '    public val isHighContrast: Boolean,',
    '    public val focusRingWidth: Float,',
    '    public val colors: MonarchColorTokens,',
    '    public val shadows: MonarchShadowTokens,',
    ') {',
    '    /**',
    '     * This theme with another accent. Replaces the accent roles and the roles',
    '     * that follow the accent in this theme (links, and the focus ring outside',
    '     * the high-contrast themes).',
    '     */',
    '    public fun withAccent(accent: MonarchAccent): MonarchThemeTokens {',
    '        val a = accent.scale(id)',
    ...ktReplace((t) => t.followers),
    '    }',
    '',
    '    /**',
    '     * This theme with a custom AI colour, such as `MonarchBrandTheme.aiAccent`.',
    '     * Replaces the AI roles and the roles that follow them (thinking and',
    '     * citation). Combine with [withAccent] for a full brand theme.',
    '     */',
    '    public fun withAi(ai: MonarchAccent): MonarchThemeTokens {',
    '        val a = ai.scale(id)',
    ...ktReplace((t) => t.aiFollowers),
    '    }',
    '}',
    '',
    '/** Monarch design tokens. Lengths are dp, type sizes are sp, durations are milliseconds. */',
    'public object MonarchTokens {',
  );
  for (const [name, list] of primitives.colors)
    obj(
      name,
      `Primitive ${name.toLowerCase()} colours. Components use theme roles, not these.`,
      consts('Long', list, ktColor),
    );
  o.push(
    '    /** Base colour of the AI intent. */',
    `    public const val intelligence: Long = ${ktColor(primitives.intelligence)}`,
    '',
  );
  for (const [name, doc, list] of primitives.lengths)
    obj(name, doc, consts('Float', list, ktFloat));
  obj('FontWeight', 'Font weights, 100 to 900.', consts('Int', primitives.fontWeight, num));
  obj(
    'LineHeight',
    'Line height as a multiple of the type size.',
    consts('Float', primitives.lineHeight, ktFloat),
  );
  obj('LetterSpacing', 'Tracking in em.', consts('Float', primitives.letterSpacing, ktFloat));
  obj('Duration', 'Motion durations in milliseconds.', consts('Int', primitives.duration, num));
  obj(
    'Easing',
    'Motion curves.',
    primitives.easing.map(
      ([n, v]) =>
        `public val ${n}: MonarchCubicBezier = MonarchCubicBezier(${v.map(ktFloat).join(', ')})`,
    ),
  );
  for (const t of themeList) {
    o.push(
      `    /** The \`${t.id}\` theme. */`,
      `    public val ${t.name}: MonarchThemeTokens = MonarchThemeTokens(`,
      `        id = "${t.id}",`,
      `        isDark = ${t.dark},`,
      `        isHighContrast = ${t.highContrast},`,
      `        focusRingWidth = ${ktFloat(t.focusRingWidth)},`,
      '        colors = MonarchColorTokens(',
      ...t.colors.map(([n, c]) => `            ${n} = ${ktColor(c)},`),
      '        ),',
      '        shadows = MonarchShadowTokens(',
      ...t.shadows.map(([n, s]) => `            ${n} = ${ktShadow(s)},`),
      '        ),',
      '    )',
      '',
    );
  }
  o.push(
    '    /** Every theme, in the order light, dark, high-contrast light, high-contrast dark. */',
    `    public val themes: List<MonarchThemeTokens> = listOf(${themeList.map((t) => t.name).join(', ')})`,
    '',
    '    /** Brand accents: the default, the neutral accent and one per Rook product. */',
    '    public object Accents {',
  );
  for (const a of accents) {
    o.push(
      `        /** ${a.label}. */`,
      `        public val ${a.ident}: MonarchAccent = MonarchAccent(`,
      `            id = "${a.id}",`,
      `            label = "${a.label}",`,
      ...themeList.map(
        (t, i) =>
          `            ${t.name} = MonarchAccentScale(${at(a.scales, i)
            .map(([, c]) => ktColor(c))
            .join(', ')}),`,
      ),
      '        )',
      '',
    );
  }
  o.push(
    `        public val all: List<MonarchAccent> = listOf(${accents.map((a) => a.ident).join(', ')})`,
    '    }',
    '}',
    '',
  );
  return o.join('\n');
}

