interface Theme {
  readonly id: ThemeId;
  readonly name: string;
  readonly dark: boolean;
  readonly highContrast: boolean;
  readonly colors: Entry<Rgba>[];
  readonly shadows: Entry<Shadow[]>[];
  readonly focusRingWidth: number;
  /**
   * Role name → accent role, for the colours that change with the accent in
   * this theme. It differs by theme: the focus ring follows the accent in the
   * standard themes and the text colour in the high-contrast ones.
   */
  readonly followers: ReadonlyMap<string, string>;
  /**
   * Role name → AI role, for the colours that change with a custom AI colour:
   * the ten `ai*` intent roles and the roles that alias them (thinking, citation).
   */
  readonly aiFollowers: ReadonlyMap<string, string>;
}

/** The intent role a token follows, by path or by alias, or null. */
function follows(intent: string, path: string, value: DtcgToken['$value']): string | null {
  const prefix = `color.${intent}.`;
  const own = path.startsWith(prefix) ? path.slice(prefix.length) : null;
  if (own && (ACCENT_ROLES as readonly string[]).includes(own)) return own;
  if (isAlias(value) && value.startsWith(`{${prefix}`)) return value.slice(prefix.length + 1, -1);
  return null;
}

function buildTheme(id: ThemeId): Theme {
  const semantic = walkTokens(files.get(DTCG_FILES.semantic(id)) as DtcgGroup);
  const all = new Map<string, DtcgToken>([...primitiveTokens, ...semantic]);
  const colors: Entry<Rgba>[] = [];
  const shadows: Entry<Shadow[]>[] = [];
  const followers = new Map<string, string>();
  const aiFollowers = new Map<string, string>();
  let focusRingWidth = 0;
  for (const [path, token] of semantic) {
    const value = resolveAlias(token.$value, all);
    if (value === null) throw new Error(`Unresolved alias at ${path} (${id})`);
    if (token.$type === 'color' && isColorValue(value)) {
      const name = camel(path.replace(/^color\./, ''));
      colors.push([name, rgbaOfDtcg(value)]);
      const accentRole = follows('accent', path, token.$value);
      if (accentRole) followers.set(name, camel(accentRole));
      const aiRole = follows('ai', path, token.$value);
      if (aiRole) aiFollowers.set(name, camel(aiRole));
    } else if (token.$type === 'shadow') {
      shadows.push([
        path.replace('shadow.', ''),
        (value as DtcgShadowLayer[]).map((l) => ({
          color: rgbaOfDtcg(l.color),
          x: l.offsetX.value,
          y: l.offsetY.value,
          blur: l.blur.value,
          spread: l.spread.value,
        })),
      ]);
    } else if (path === 'focus.ring-width' && isDimensionValue(value)) {
      focusRingWidth = value.value;
    } else {
      throw new Error(`No native output for ${path} (${token.$type})`);
    }
  }
  if (shadows.map(([n]) => n).join() !== SHADOW_SIZES.join())
    throw new Error(`Unexpected shadow sizes in ${id}`);
  return {
    id,
    name: camel(id),
    dark: themes[id].scheme === 'dark',
    highContrast: themes[id].contrast === 'more',
    colors,
    shadows,
    focusRingWidth,
    followers,
    aiFollowers,
  };
}

const themeList = THEME_IDS.map(buildTheme);
/** The light theme: the default branch wherever code switches on a theme id. */
const baseTheme = at(themeList, 0);
const roleNames = baseTheme.colors.map(([n]) => n);
for (const t of themeList)
  if (t.colors.map(([n]) => n).join() !== roleNames.join())
    throw new Error(`Theme ${t.id} has a different set of colour roles`);

interface Accent {
  readonly id: string;
  readonly ident: string;
  readonly label: string;
  /** One scale per theme, in THEME_IDS order. */
  readonly scales: Entry<Rgba>[][];
}
const accent = (id: string, label: string, base: Hsl): Accent => ({
  id,
  ident: camel(id),
  label,
  scales: THEME_IDS.map((t) => {
    const scale = resolveTheme(themes[t], base).intents.accent;
    return ACCENT_ROLES.map((r): Entry<Rgba> => [camel(r), rgbaOfCss(scale[r])]);
  }),
});
const accents: Accent[] = [
  accent('rook', 'Rook Red, the default', p.defaultAccent),
  accent(NEUTRAL_ACCENT_ID, 'Neutral slate, for apps outside Rook', neutralAccent),
  ...Object.values(products).map((x) => accent(x.id, x.name, x.accent)),
];
// The default accent must reproduce the accent roles the themes were built with.
for (const [i, t] of themeList.entries()) {
  const byName = new Map(t.colors);
  for (const [role, c] of at(at(accents, 0).scales, i)) {
    const themed = byName.get(`accent${cap(role)}`);
    if (!themed || themed.rgb !== c.rgb)
      throw new Error(`Default accent mismatch: ${t.id} ${role}`);
  }
}

