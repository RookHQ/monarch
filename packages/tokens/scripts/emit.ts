/**
 * Step 3 of the build: emit CSS, DTCG JSON and the contrast report into dist/.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  buildCompatCss,
  buildMonarchCss,
  buildProductCss,
  NEUTRAL_ROLES,
  INTENT_ROLES,
} from '../src/css.js';
import { toCss, toHex } from '../src/color.js';
import { defaultAccent } from '../src/primitives.js';
import * as primitives from '../src/primitives.js';
import { INTENT_IDS, THEME_IDS, resolveTheme, themes } from '../src/themes.js';
import { products, productIds } from '../src/generated/products.js';

const dist = join(dirname(fileURLToPath(import.meta.url)), '../dist');
mkdirSync(join(dist, 'css/products'), { recursive: true });

const write = (rel: string, content: string) => {
  writeFileSync(join(dist, rel), content);
  return Buffer.byteLength(content);
};

const BASE_CSS = `/*! Monarch base styles. Optional. Generated by @rookcom/monarch-tokens. */
@layer monarch.tokens, monarch.base, monarch.components;

@layer monarch.base {
  html {
    -webkit-text-size-adjust: 100%;
    text-rendering: optimizeLegibility;
    -webkit-font-smoothing: antialiased;
    -moz-osx-font-smoothing: grayscale;
  }
  body {
    background: var(--mn-color-bg-canvas);
    color: var(--mn-color-text-default);
    font-family: var(--mn-font-sans);
  }
  :where(a[href], button, input, select, textarea, summary, [tabindex]:not([tabindex='-1']), [role='button'], [role='tab'], [role='menuitem'], [role='option']):focus-visible {
    outline: var(--mn-focus-ring-width) solid var(--mn-color-focus-ring);
    outline-offset: 2px;
  }
  ::selection {
    background: color-mix(in srgb, var(--mn-color-accent-strong) 22%, transparent);
  }
  @media (prefers-reduced-motion: reduce) {
    *, *::before, *::after {
      animation-duration: 0.01ms !important;
      animation-iteration-count: 1 !important;
      transition-duration: 0.01ms !important;
      scroll-behavior: auto !important;
    }
  }
}
`;

const sizes: Record<string, number> = {};
sizes['css/monarch.css'] = write('css/monarch.css', buildMonarchCss(defaultAccent));
sizes['css/compat.css'] = write('css/compat.css', buildCompatCss(defaultAccent));
sizes['css/base.css'] = write('css/base.css', BASE_CSS);
for (const id of productIds) {
  sizes[`css/products/${id}.css`] = write(
    `css/products/${id}.css`,
    buildProductCss(id, products[id].accent),
  );
}

// DTCG-style token document for design tools and non-React consumers.
const color = (h: Parameters<typeof toCss>[0]) => ({
  $type: 'color',
  $value: toHex(h),
  $extensions: { 'com.rookhq.monarch': { hsl: toCss(h) } },
});
const themesJson = Object.fromEntries(
  THEME_IDS.map((id) => {
    const r = resolveTheme(themes[id], defaultAccent);
    const neutrals = Object.fromEntries(
      NEUTRAL_ROLES.map((role) => [role, color(r.theme.neutrals[role])]),
    );
    const intents = Object.fromEntries(
      INTENT_IDS.map((i) => [
        i,
        Object.fromEntries(INTENT_ROLES.map((role) => [role, color(r.intents[i][role])])),
      ]),
    );
    return [id, { color: { ...neutrals, ...intents } }];
  }),
);
const dim = (v: string) => ({ $type: 'dimension', $value: v });
write(
  'tokens.json',
  JSON.stringify(
    {
      $description: 'Rook Monarch design tokens',
      font: {
        family: Object.fromEntries(
          Object.entries(primitives.fontFamily).map(([k, v]) => [
            k,
            { $type: 'fontFamily', $value: v },
          ]),
        ),
        size: Object.fromEntries(Object.entries(primitives.fontSize).map(([k, v]) => [k, dim(v)])),
        weight: Object.fromEntries(
          Object.entries(primitives.fontWeight).map(([k, v]) => [
            k,
            { $type: 'fontWeight', $value: Number(v) },
          ]),
        ),
      },
      space: Object.fromEntries(Object.entries(primitives.space).map(([k, v]) => [k, dim(v)])),
      radius: Object.fromEntries(Object.entries(primitives.radius).map(([k, v]) => [k, dim(v)])),
      duration: Object.fromEntries(
        Object.entries(primitives.duration).map(([k, v]) => [k, { $type: 'duration', $value: v }]),
      ),
      themes: themesJson,
    },
    null,
    2,
  ) + '\n',
);

// Contrast report: every product × theme, with each adjustment explained.
const report = {
  generatedBy: '@rookcom/monarch-tokens',
  products: Object.fromEntries(
    [
      ['default', defaultAccent] as const,
      ...productIds.map((id) => [id, products[id].accent] as const),
    ].map(([id, accent]) => [
      id,
      Object.fromEntries(THEME_IDS.map((t) => [t, resolveTheme(themes[t], accent).reports.accent])),
    ]),
  ),
  status: Object.fromEntries(
    THEME_IDS.map((t) => {
      const r = resolveTheme(themes[t], defaultAccent);
      return [
        t,
        Object.fromEntries(INTENT_IDS.filter((i) => i !== 'accent').map((i) => [i, r.reports[i]])),
      ];
    }),
  ),
};
write('contrast-report.json', JSON.stringify(report, null, 2) + '\n');

const total = Object.values(sizes).reduce((a, b) => a + b, 0);
console.log(
  `emitted ${Object.keys(sizes).length} css files (${(total / 1024).toFixed(1)} KiB); monarch.css ${((sizes['css/monarch.css'] ?? 0) / 1024).toFixed(1)} KiB`,
);
