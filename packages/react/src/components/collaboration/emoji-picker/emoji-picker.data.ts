/**
 * A compact built-in emoji set: about 500 common emoji in nine categories,
 * with English names (Unicode CLDR short names) and search keywords. It keeps
 * Monarch without an emoji dataset dependency. Products that need every
 * emoji can load a full dataset and pass it as `categories`.
 */

export type EmojiCategoryId =
  | 'recent'
  | 'smileys'
  | 'people'
  | 'animals'
  | 'food'
  | 'travel'
  | 'activities'
  | 'objects'
  | 'symbols'
  | 'flags';

export interface EmojiPickerItem {
  /** The emoji character sequence, inserted as is. */
  emoji: string;
  /** English name, read by screen readers and shown in the preview, e.g. "thumbs up". */
  name: string;
  /** Extra search words, e.g. `['like', 'yes']`. */
  keywords?: readonly string[] | undefined;
  /** The emoji accepts a skin tone modifier. Only set it on single code point emoji. */
  skinTones?: boolean | undefined;
}

export interface EmojiPickerCategory {
  /** Stable id. Built-in ids are named by `messages.categories`. */
  id: string;
  /** Category name. Default: `messages.categories[id]`, then the id. */
  label?: string | undefined;
  /** Emoji shown on the category tab. Default: the first emoji. */
  icon?: string | undefined;
  emojis: readonly EmojiPickerItem[];
}

type Row = readonly [emoji: string, name: string, keywords?: string, tone?: 1];

function cat(id: EmojiCategoryId, icon: string, rows: readonly Row[]): EmojiPickerCategory {
  return {
    id,
    icon,
    emojis: rows.map(([emoji, name, keywords, tone]) => ({
      emoji,
      name,
      ...(keywords ? { keywords: keywords.split(' ') } : {}),
      ...(tone ? { skinTones: true } : {}),
    })),
  };
}

